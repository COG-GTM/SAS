"""Markdown rendering of the parity results (numbers come only from parity_results of the latest run)."""
from __future__ import annotations

import datetime as dt


def render_report(results, fmt) -> str:
    ds = [r for x in results for r in x["datasets"]]
    n_pass = sum(r["status"] == "PASS" for r in ds)
    n_diff = sum(r["status"] == "DIFF" for r in ds)
    n_miss = len(ds) - n_pass - n_diff
    cls = {}
    for r in ds:
        if r["status"] == "DIFF":
            cls[r["classification"]] = cls.get(r["classification"], 0) + 1
    rows = sum(r.get("rows_compared", 0) for r in ds)
    cells = sum(r.get("cells_compared", 0) for r in ds)
    out = [
        "# SAS (blackbox engine) vs PySpark parity report",
        "",
        f"Generated by `parity/run_parity.sh` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M UTC}. "
        "Every number below is computed from the SAS-engine and PySpark outputs of that run "
        "(`parity/build/parity_results.json`).",
        "",
        "![summary](parity_summary.png)",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Cases (SAS programs run in one session each) | {len(results)} |",
        f"| SAS book programs / setup blocks covered | {sum(len(x['case'].steps) for x in results)} |",
        f"| Datasets compared | {len(ds)} |",
        f"| **PASS** (schema + row count + every value) | **{n_pass}** |",
        f"| DIFF | {n_diff} |",
        f"| Missing on one side | {n_miss} |",
        f"| SAS output rows compared | {rows} |",
        f"| Cells compared | {cells} |",
        f"| SAS log ERROR lines | {sum(x['sas']['error_count'] for x in results)} |",
        f"| SAS runs with non-zero exit code | {sum(1 for x in results if x['sas']['rc'] != 0)} |",
        f"| SAS log `NOTE: Invalid data` lines (expected: deliberately malformed mock fields) | "
        f"{sum(x['sas']['invalid_data_notes'] for x in results)} |",
        f"| PySpark job failures | {sum(1 for x in results if x['pyspark']['error'])} |",
    ]
    for k, v in sorted(cls.items()):
        out.append(f"| DIFF classified {k} | {v} |")
    out += ["", "Tolerance: numeric |a-b| <= 1e-9 + 1e-9*max(|a|,|b|); character values compared after removing "
            "trailing blanks; SAS missing == Spark NULL.", "", "## Per case", "",
            "| Case | What it exercises | SAS steps | Datasets | PASS | DIFF | SAS rows | SAS rc | SAS run (s) | PySpark (s) |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for x in results:
        c, d = x["case"], x["datasets"]
        steps = ", ".join(s.split(":", 1)[1] for s, _ in c.steps)
        out.append(f"| `{c.id}` | {c.title} | {steps} | {len(d)} | {sum(r['status'] == 'PASS' for r in d)} | "
                   f"{sum(r['status'] == 'DIFF' for r in d)} | {sum(r.get('rows_sas', 0) for r in d)} | "
                   f"{x['sas']['rc']}{' **FAILED**' if x['sas']['rc'] else ''} | "
                   f"{x['sas']['seconds']} | {x['pyspark']['seconds']} |")
    out += ["", "## Per dataset", "", "| Case | Step | Dataset | Status | Rows SAS / PySpark | Cols | Cells | Note |",
            "|---|---|---|---|---|---|---|---|"]
    for x in results:
        for r in x["datasets"]:
            note = r.get("classification", "") + (" (unordered)" if r["unordered"] else "")
            out.append(f"| `{x['case'].id}` | {r['step']} | {r['dataset']} | {r['status']} | "
                       f"{r.get('rows_sas', '-')} / {r.get('rows_pyspark', '-')} | {r.get('cols_sas', '-')} | "
                       f"{r.get('cells_compared', 0)} | {note} |")
    from triage import FIXED
    out += ["", "## Translation bugs found and fixed", "",
            "Found by earlier runs of this harness; the numbers above are from the run after the fixes.", ""]
    out += [f"- **{what}** — {how}" for what, how in FIXED]
    diffs = [(x, r) for x in results for r in x["datasets"] if r["status"] != "PASS"]
    out += ["", "## Differences", ""]
    if not diffs:
        out.append("None.")
    for x, r in diffs:
        out += [f"### `{r['label']}` ({x['case'].id}, {r['step']}) — {r.get('classification', r['status'])}", ""]
        if r.get("explanation"):
            out += [r["explanation"], ""]
        for i in r["issues"]:
            out.append(f"- {i}")
        for col, e in r.get("mismatches", {}).items():
            ex = "; ".join(f"row {m['row']}: SAS={fmt(m['sas'])} PySpark={fmt(m['pyspark'])}" for m in e["examples"])
            out.append(f"  - `{col}`: {e['count']} value(s) differ, e.g. {ex}")
        out.append("")
    return "\n".join(out) + "\n"
